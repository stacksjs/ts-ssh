/**
 * The handshake, driven by the real OpenSSH client.
 *
 * Every other test in this package checks one layer against the RFC that
 * defines it. This one checks the whole thing against the program people
 * actually use, and it is the only test here whose failure is unambiguous: if
 * `ssh` cannot log in and run a command, the library is wrong, whatever the
 * unit tests say.
 *
 * It has already earned its place. The four megabyte transfer below failed the
 * first time it ran, with `message authentication code incorrect` after 320 KiB
 * - a socket whose `write` had taken fewer bytes than it was given, which
 * truncates the stream and is indistinguishable from tampering. That is now
 * `socket.ts`'s problem rather than every caller's.
 *
 * The client keys these tests use are generated by `formatPrivateKey`, so the
 * key writer is checked by a program that did not write it. A generator that
 * only its own parser accepts has invented a private format, and this is what
 * would notice.
 */

import type { Subprocess } from 'bun'
import type { Server } from '../src'
import { spawn } from 'bun'
import { afterAll, describe, expect, it } from 'bun:test'
import { chmodSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { generateHostKey, serve } from '../src'

const workspace = mkdtempSync(join(tmpdir(), 'ts-ssh-'))
afterAll(() => rmSync(workspace, { recursive: true, force: true }))

const host = generateHostKey('host')
const client = generateHostKey('client@test')
const other = generateHostKey('other@test')

const clientKeyPath = writeKey('id_ed25519', client.openssh)
const otherKeyPath = writeKey('id_other', other.openssh)

function writeKey(name: string, contents: string): string {
  const path = join(workspace, name)
  writeFileSync(path, contents)
  // ssh refuses a private key anybody else can read, which is a good rule and
  // an obscure test failure the first time you meet it.
  chmodSync(path, 0o600)

  return path
}

interface Behaviour {
  /** What a command produces. */
  exec?: (command: string) => { stdout?: Uint8Array, stderr?: Uint8Array, status?: number }
  /** Echo stdin back instead of answering immediately. */
  echo?: boolean
  /** Report which key authenticated, rather than running anything. */
  identify?: boolean
  /** Which client keys are allowed in. Every key, by default. */
  allows?: (blob: Uint8Array) => boolean
  allow?: readonly string[]
}

function server(behaviour: Behaviour): Server {
  return serve({
    hostKey: host.key,
    allow: behaviour.allow,
    authenticate: attempt => behaviour.allows?.(attempt.blob) ?? true,
    onError: error => console.error('server:', error),

    onCommand(command) {
      if (behaviour.identify) {
        const blob = Buffer.from(command.keyBlob).toString('base64')
        command.write(`${command.command} as ${command.user} with ${command.key.type} ${blob}\n`)
        command.exit(0)

        return
      }

      if (behaviour.echo) {
        const chunks: Uint8Array[] = []
        command.onData(data => chunks.push(data))
        command.onEnd(() => {
          for (const chunk of chunks)
            command.write(chunk)

          command.exit(0)
        })

        return
      }

      const result = behaviour.exec?.(command.command) ?? { status: 0 }

      if (result.stderr)
        command.writeStderr(result.stderr)
      if (result.stdout)
        command.write(result.stdout)

      command.exit(result.status ?? 0)
    },
  })
}

/** Run the real client against a server, and collect what it saw. */
async function ssh(port: number, command: string, options: {
  key?: string
  args?: string[]
  stdin?: string
} = {}): Promise<{ stdout: Uint8Array, text: string, stderr: string, code: number }> {
  const child: Subprocess = spawn({
    cmd: [
      'ssh',
      '-i', options.key ?? clientKeyPath,
      '-p', String(port),
      '-o', 'IdentitiesOnly=yes',
      // Without this the client offers whatever is in the developer's own
      // agent, which passes for the wrong reason and fails on a machine that
      // has no agent at all.
      '-o', 'IdentityAgent=none',
      '-o', 'StrictHostKeyChecking=no',
      '-o', 'UserKnownHostsFile=/dev/null',
      '-o', 'BatchMode=yes',
      '-o', 'LogLevel=ERROR',
      ...(options.args ?? []),
      'someone@127.0.0.1',
      command,
    ],
    stdin: options.stdin === undefined ? 'ignore' : new TextEncoder().encode(options.stdin),
    stdout: 'pipe',
    stderr: 'pipe',
  })

  const [stdout, stderr, code] = await Promise.all([
    new Response(child.stdout as ReadableStream).arrayBuffer(),
    new Response(child.stderr as ReadableStream).text(),
    child.exited,
  ])

  const bytes = new Uint8Array(stdout)

  return { stdout: bytes, text: new TextDecoder().decode(bytes), stderr, code }
}

function bytes(text: string): Uint8Array {
  return new TextEncoder().encode(text)
}

describe('a real OpenSSH client', () => {
  it('logs in with a key and runs a command', async () => {
    const running = server({ exec: command => ({ stdout: bytes(`ran: ${command}\n`) }) })

    try {
      const result = await ssh(running.port, 'echo hello')

      expect(result.code).toBe(0)
      expect(result.text).toBe('ran: echo hello\n')
    }
    finally {
      running.stop()
    }
  })

  it('passes the exit status back', async () => {
    const running = server({ exec: () => ({ status: 42 }) })

    try {
      // A client that gets a close with no exit status has to assume the worst,
      // so a server that forgets this makes every command look like it failed.
      expect((await ssh(running.port, 'anything')).code).toBe(42)
    }
    finally {
      running.stop()
    }
  })

  it('keeps stdout and stderr apart', async () => {
    const running = server({ exec: () => ({ stdout: bytes('out'), stderr: bytes('err') }) })

    try {
      const result = await ssh(running.port, 'both')

      expect(result.text).toBe('out')
      expect(result.stderr).toContain('err')
    }
    finally {
      running.stop()
    }
  })

  it('refuses a key the server does not know', async () => {
    const running = server({ allows: blob => Buffer.from(blob).equals(Buffer.from(client.key.publicKey)) })

    try {
      const result = await ssh(running.port, 'echo hello', { key: otherKeyPath })

      expect(result.code).not.toBe(0)
      expect(result.stderr).toContain('Permission denied')
    }
    finally {
      running.stop()
    }
  })

  it('refuses a shell, which is what a forge wants', async () => {
    const running = server({ exec: () => ({ status: 0 }) })

    try {
      // No command means a shell request, and `exec` heads the default allow
      // list for a reason: a forge runs git for people who have no account on
      // the machine.
      expect((await ssh(running.port, '')).code).not.toBe(0)
    }
    finally {
      running.stop()
    }
  })

  it('carries more than one window of data', async () => {
    // Four megabytes against a two megabyte window: this cannot complete unless
    // the window adjustments are right in both directions and the socket
    // backlog is honoured. It is also the smallest thing resembling a clone.
    const payload = new Uint8Array(4 * 1024 * 1024)
    for (let index = 0; index < payload.length; index++)
      payload[index] = index % 251

    const running = server({ exec: () => ({ stdout: payload }) })

    try {
      const result = await ssh(running.port, 'big')

      expect(result.code).toBe(0)
      expect(result.stdout.length).toBe(payload.length)
      expect(result.stdout[0]).toBe(payload[0])
      expect(result.stdout[payload.length - 1]).toBe(payload[payload.length - 1])
      expect(Buffer.from(result.stdout).equals(Buffer.from(payload))).toBe(true)
    }
    finally {
      running.stop()
    }
  }, 60_000)

  it('reads what the client sends on stdin', async () => {
    const running = server({ echo: true })

    try {
      const result = await ssh(running.port, 'cat', { stdin: 'the quick brown fox\n' })

      expect(result.code).toBe(0)
      expect(result.text).toBe('the quick brown fox\n')
    }
    finally {
      running.stop()
    }
  })

  it('works over aes256-ctr with an encrypt-then-mac hmac', async () => {
    const running = server({ exec: () => ({ stdout: bytes('ctr\n') }) })

    try {
      // The other half of the cipher module. GCM is what gets negotiated by
      // default, so without forcing it the CTR path is never exercised by a
      // real client - and it is the path with a separate MAC to get wrong.
      const result = await ssh(running.port, 'echo', {
        args: ['-o', 'Ciphers=aes256-ctr', '-o', 'MACs=hmac-sha2-512-etm@openssh.com'],
      })

      expect(result.code).toBe(0)
      expect(result.text).toBe('ctr\n')
    }
    finally {
      running.stop()
    }
  })

  it('negotiates a strict key exchange', async () => {
    const running = server({ exec: () => ({ stdout: bytes('ok\n') }) })

    try {
      const result = await ssh(running.port, 'echo', { args: ['-vv', '-o', 'LogLevel=DEBUG2'] })

      expect(result.code).toBe(0)
      // Resetting the sequence numbers at NEWKEYS is what strict mode *is*, and
      // the client only does it when it saw our marker. Asserting on the effect
      // rather than on a log line about the feature: this is the client saying
      // it changed its own behaviour because of what we sent.
      expect(result.stderr).toContain('resetting send seqnr')
      expect(result.stderr).toContain('resetting read seqnr')
    }
    finally {
      running.stop()
    }
  })

  it('tells the command which key authenticated', async () => {
    const running = server({ identify: true })

    try {
      const result = await ssh(running.port, 'whoami')

      expect(result.code).toBe(0)
      // The name is what the client typed; the key is what it had to prove. A
      // forge where everybody connects as `git@` has only the second to go on.
      expect(result.text).toContain('whoami as someone with ssh-ed25519 ')
      expect(result.text.trim()).toEndWith(Buffer.from(client.key.publicKey).toString('base64'))
    }
    finally {
      running.stop()
    }
  })

  it('survives a client that hangs up mid handshake', async () => {
    const running = server({ exec: () => ({ status: 0 }) })

    try {
      // Half a version line and then nothing. A server that throws here takes
      // down every other connection with it, and this is what a port scanner
      // does all day.
      const socket = await Bun.connect({
        hostname: '127.0.0.1',
        port: running.port,
        socket: { data() {} },
      })
      socket.write(new TextEncoder().encode('SSH-2.0-half'))
      socket.end()

      // The server is still serving.
      expect((await ssh(running.port, 'after')).code).toBe(0)
    }
    finally {
      running.stop()
    }
  })
})
